// Command gen-tenant-tables scans schema/migrations/postgres/*.sql for ALTER TABLE ... ENABLE ROW LEVEL SECURITY statements and writes schema/tenant_tables_gen.go with the sorted list of tenant-scoped table suffixes (post-{{.TablePrefix}}).
package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// enableRLSRe matches `ALTER TABLE {{.Schema}}.{{.TablePrefix}}<name> ENABLE ROW LEVEL SECURITY;`
var enableRLSRe = regexp.MustCompile(`(?is)ALTER\s+TABLE\s+(?:{{\.Schema}}\.)?{{\.TablePrefix}}(\w+)\s+ENABLE\s+ROW\s+LEVEL\s+SECURITY\s*;`)

func main() {
	root, err := moduleRoot()
	if err != nil {
		die("locate module root: %v", err)
	}
	migrationsDir := filepath.Join(root, "schema", "migrations", "postgres")
	outFile := filepath.Join(root, "schema", "tenant_tables_gen.go")

	entries, err := os.ReadDir(migrationsDir)
	if err != nil {
		die("read migrations dir: %v", err)
	}
	seen := map[string]struct{}{}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".sql") {
			continue
		}
		body, err := os.ReadFile(filepath.Join(migrationsDir, e.Name())) //nolint:gosec // G304: migrationsDir is a fixed sub-path of the module root, not tainted input.
		if err != nil {
			die("read %s: %v", e.Name(), err)
		}
		for _, m := range enableRLSRe.FindAllSubmatch(body, -1) {
			seen[string(m[1])] = struct{}{}
		}
	}
	names := make([]string, 0, len(seen))
	for n := range seen {
		names = append(names, n)
	}
	slices.Sort(names)

	var b strings.Builder
	b.WriteString("// Code generated by schema/cmd/gen-tenant-tables. DO NOT EDIT.\n\n")
	b.WriteString("package schema\n\n")
	b.WriteString("// TenantTableSuffixes lists every table (without TablePrefix) that carries an org_id column and therefore participates in RLS.\n")
	b.WriteString("var TenantTableSuffixes = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	b.WriteString("}\n\n")
	b.WriteString("// TenantTableNames returns TenantTableSuffixes prefixed with the given TablePrefix.\n")
	b.WriteString("func TenantTableNames(prefix string) []string {\n")
	b.WriteString("\tout := make([]string, len(TenantTableSuffixes))\n")
	b.WriteString("\tfor i, s := range TenantTableSuffixes {\n")
	b.WriteString("\t\tout[i] = prefix + s\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn out\n")
	b.WriteString("}\n")

	if err := os.WriteFile(outFile, []byte(b.String()), 0o644); err != nil { //nolint:gosec // G306: generated Go source, not a secret
		die("write %s: %v", outFile, err)
	}
	fmt.Fprintf(os.Stderr, "gen-tenant-tables: wrote %s (%d tables: %s)\n", outFile, len(names), strings.Join(names, ", "))
}

func moduleRoot() (string, error) {
	out, err := exec.Command("go", "env", "GOMOD").Output()
	if err != nil {
		return "", err
	}
	goMod := strings.TrimSpace(string(out))
	if goMod == "" || goMod == "/dev/null" {
		return "", fmt.Errorf("no go.mod found")
	}
	return filepath.Dir(goMod), nil
}

func die(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen-tenant-tables: "+format+"\n", args...)
	os.Exit(1)
}
